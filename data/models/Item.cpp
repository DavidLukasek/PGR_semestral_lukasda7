#include <iostream>
#include "Item.h"

Item::Item(ShaderProgram* shdrPrg)
    : SingleMesh("square", shdrPrg, nullptr)
    , initialized(false) {
    initializeItem();
}

Item::~Item() {
    if (geometry != nullptr) {
        glDeleteVertexArrays(1, &(geometry->vertexArrayObject));
        glDeleteBuffers(1, &(geometry->normalBufferObject));
        glDeleteBuffers(1, &(geometry->texCoordBufferObject));
        glDeleteBuffers(1, &(geometry->elementBufferObject));
        glDeleteBuffers(1, &(geometry->vertexBufferObject));
        glDeleteTextures(1, &(geometry->diffuseTextureObject));
        glDeleteTextures(1, &(geometry->normalTextureObject));

        delete geometry;
        geometry = nullptr;
    }

    initialized = false;
}

void Item::draw(const glm::mat4& viewMatrix, const glm::mat4& projectionMatrix) {
    if (initialized && (shaderProgram != nullptr) && (geometry != nullptr)) {
        glUseProgram(shaderProgram->program);
        applyMaterialUniforms();

        if (shaderProgram->locations.projectionMatrix != -1) {
            glUniformMatrix4fv(shaderProgram->locations.projectionMatrix,
                               1, GL_FALSE, glm::value_ptr(projectionMatrix));
        }

        if (shaderProgram->locations.viewMatrix != -1) {
            glUniformMatrix4fv(shaderProgram->locations.viewMatrix,
                               1, GL_FALSE, glm::value_ptr(viewMatrix));
        }

        if (shaderProgram->locations.modelMatrix != -1) {
            glUniformMatrix4fv(shaderProgram->locations.modelMatrix,
                               1, GL_FALSE, glm::value_ptr(globalModelMatrix));
        }

        if (shaderProgram->locations.normalMatrix != -1) {
            const glm::mat4 normalMatrix = glm::transpose(glm::inverse(globalModelMatrix));
            glUniformMatrix4fv(shaderProgram->locations.normalMatrix,
                               1, GL_FALSE, glm::value_ptr(normalMatrix));
        }

        if (shaderProgram->locations.hasDiffuseTexture != -1)
            glUniform1i(shaderProgram->locations.hasDiffuseTexture, 0);

        if (shaderProgram->locations.hasNormalTexture != -1)
            glUniform1i(shaderProgram->locations.hasNormalTexture, 0);

        glBindVertexArray(geometry->vertexArrayObject);
        glDrawElements(GL_TRIANGLES, geometry->numTriangles * 3, GL_UNSIGNED_INT, 0);
        glBindVertexArray(0);
    }
    else {
        std::cerr << "Item::draw(): Can't draw, mesh not initialized properly!" << std::endl;
    }

    Object::draw(viewMatrix, projectionMatrix);
}

void Item::initializeItem() {
    geometry = new ObjectGeometry;

    geometry->numTriangles = nTriangles;
    geometry->normalBufferObject = 0;
    geometry->texCoordBufferObject = 0;
    geometry->diffuseTextureObject = 0;
    geometry->normalTextureObject = 0;
    geometry->hasTexture = false;
    geometry->hasNormalTexture = false;

    glGenVertexArrays(1, &(geometry->vertexArrayObject));
    glBindVertexArray(geometry->vertexArrayObject);

    glGenBuffers(1, &(geometry->vertexBufferObject));
    glBindBuffer(GL_ARRAY_BUFFER, geometry->vertexBufferObject);
    glBufferData(GL_ARRAY_BUFFER, nVertices * nAttribsPerVertex * sizeof(float), vertices, GL_STATIC_DRAW);

    glGenBuffers(1, &(geometry->elementBufferObject));
    glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, geometry->elementBufferObject);
    glBufferData(GL_ELEMENT_ARRAY_BUFFER, nTriangles * 3 * sizeof(unsigned), triangles, GL_STATIC_DRAW);

    if ((shaderProgram != nullptr) &&
        shaderProgram->initialized &&
        (shaderProgram->locations.position != -1)) {

        glEnableVertexAttribArray(shaderProgram->locations.position);
        glVertexAttribPointer(shaderProgram->locations.position, 3, GL_FLOAT,
                              GL_FALSE, nAttribsPerVertex * sizeof(float), (void*)0);

        if (shaderProgram->locations.normal != -1) {
            glEnableVertexAttribArray(shaderProgram->locations.normal);
            glVertexAttribPointer(shaderProgram->locations.normal, 3, GL_FLOAT,
                                  GL_FALSE, nAttribsPerVertex * sizeof(float),
                                  (void*)(3 * sizeof(float)));
        }

        if (shaderProgram->locations.texCoord != -1) {
            glEnableVertexAttribArray(shaderProgram->locations.texCoord);
            glVertexAttribPointer(shaderProgram->locations.texCoord, 2, GL_FLOAT,
                                  GL_FALSE, nAttribsPerVertex * sizeof(float),
                                  (void*)(6 * sizeof(float)));
        }

        initialized = true;
    }
    else {
        std::cerr << "Item::initializeItem(): shaderProgram struct not initialized!"
                  << std::endl;
    }

    glBindVertexArray(0);
}

